    c_rand = c_bench[(c_bench["model"] == "logistic") & (c_bench["split_type"] == "random")]
    c_loeo = c_bench[(c_bench["model"] == "logistic") & (c_bench["split_type"] == "loeo")]
    c_loro = c_bench[(c_bench["model"] == "logistic") & (c_bench["split_type"] == "loro")]
    c_lodto = c_bench[(c_bench["model"] == "logistic") & (c_bench["split_type"] == "lodto")]

    # HumAID Splits
    h_rand = h_bench[(h_bench["model"] == "logistic") & (h_bench["split_type"] == "random")]
    h_loeo = h_bench[(h_bench["model"] == "logistic") & (h_bench["split_type"] == "loeo")]
    h_loro = h_bench[(h_bench["model"] == "logistic") & (h_bench["split_type"] == "loro")]
    h_lodto = h_bench[(h_bench["model"] == "logistic") & (h_bench["split_type"] == "lodto")]

    # Event-Prior Margins (LOEO Acc - Event Prior Acc)
