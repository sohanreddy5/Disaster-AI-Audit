    macros.append("% --- Tail Collapse Drops ---")
    macros.append(f"\\newcommand{{\\cTailDropMean}}{{{fmt(c_tail_drop_mean, 1)}}}")
    macros.append(f"\\newcommand{{\\cTailDropLow}}{{{fmt(c_tail_drop_low, 1)}}}")
    macros.append(f"\\newcommand{{\\hTailDropMean}}{{{fmt(h_tail_drop_mean, 1)}}}")
    macros.append(f"\\newcommand{{\\hTailDropLow}}{{{fmt(h_tail_drop_low, 1)}}}")

