    macros.append("% --- Average Macro LOEO Drops ---")
    macros.append(f"\\newcommand{{\\cMacroLOEODrop}}{{{fmt(c_macro_drop, 2)}}}")
    macros.append(f"\\newcommand{{\\hMacroLOEODrop}}{{{fmt(h_macro_drop, 2)}}}")

