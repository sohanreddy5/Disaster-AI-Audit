#!/usr/bin/env python3
"""Generate all publication LaTeX tables and semantic number macros from benchmark CSVs.

Ensures the PDF, Markdown manuscript, and README are mathematically tied to
the single source of truth in outputs/.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Dict, List

import numpy as np
import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parent.parent

def fmt(val: float, decimals: int = 2) -> str:
    """Format float to fixed decimals."""
    if np.isnan(val):
        return "--"
    return f"{val:.{decimals}f}"


def escape_latex(s: str) -> str:
    """Escape LaTeX special characters in strings."""
    return str(s).replace("_", "\\_").replace("&", "\\&").replace("%", "\\%")


def main() -> None:
    paper_dir = PROJECT_ROOT / "docs" / "paper"
    paper_dir.mkdir(parents=True, exist_ok=True)
    out_dir = PROJECT_ROOT / "outputs"

    macros: List[str] = [
        "% Auto-generated by scripts/generate_tables_and_macros.py",
        "% DO NOT EDIT MANUALLY. Run python scripts/generate_tables_and_macros.py to update.",
        "",
    ]

    # =========================================================================
    # 1. Benchmark Splits & Paired Shifts
    # =========================================================================
    c_diag = pd.read_csv(out_dir / "diagnostics" / "crisismmd_paired_shift_events.csv")
    h_diag = pd.read_csv(out_dir / "diagnostics" / "humaid_paired_shift_events.csv")

    c_bench = pd.read_csv(out_dir / "benchmark" / "crisismmd_benchmark_results.csv")
    h_bench = pd.read_csv(out_dir / "benchmark" / "humaid_benchmark_results.csv")

